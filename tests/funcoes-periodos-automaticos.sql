begin;
do $$
declare u uuid; a uuid; hoje date:=(now() at time zone 'America/Sao_Paulo')::date; principal uuid; pai uuid; banco uuid; sabado uuid; corrente uuid; extras uuid[]; ps jsonb; antes bigint; falhou boolean:=false; lista_dev uuid; lista_principal uuid;
begin
 select x.auth_id into a from public.usuarios x join public.usuario_funcoes uf on uf.usuario_id=x.id join public.funcoes f on f.id=uf.funcao_id where f.nome='Tesoureiro' and x.auth_id is not null limit 1;
 perform set_config('request.jwt.claim.sub',a::text,true);
 select x.id into u from public.usuarios x join public.desenvolvimento_periodos d on d.usuario_id=x.id where x.status='ativo' and x.data_entrada_tufra<hoje-10 limit 1;
 assert u is not null,'Fixture ausente';
 select id into principal from public.funcoes where nome='Médium Corrente Principal';
 select id into pai from public.funcoes where nome='Médium em Desenvolvimento';
 select id into banco from public.funcoes where nome='Banco do Desenvolvimento';
 select id into sabado from public.funcoes where nome='Banco sábado';
 select id into corrente from public.funcoes where nome='Corrente do Desenvolvimento';
 select coalesce(array_agg(funcao_id),array[]::uuid[]) into extras from public.usuario_funcoes where usuario_id=u and funcao_id<>all(array[principal,pai,banco,sabado,corrente]);
 select id into lista_dev from public.tipos_lista_presenca where nome='Desenvolvimento';
 select id into lista_principal from public.tipos_lista_presenca where nome='Corrente Principal';
 select count(*) into antes from public.presencas;
 perform private.salvar_periodos_desenvolvimento(u,jsonb_build_array(jsonb_build_object('grupo','banco_terca','data_inicio',hoje-10,'data_fim',null)));
 perform public.salvar_funcoes_com_periodo(u,extras||array[principal]);
 assert exists(select 1 from public.desenvolvimento_periodos where usuario_id=u and grupo='principal' and data_inicio=hoje and data_fim is null),'Data automática Principal';
 assert not exists(select 1 from public.usuario_funcoes where usuario_id=u and funcao_id=pai),'Desenvolvimento ainda marcado';
 assert exists(select 1 from public.listar_associados_presenca_periodo(lista_dev,hoje-1) where id=u),'Histórico de terça perdido';
 assert exists(select 1 from public.listar_associados_presenca_periodo(lista_principal,hoje) where id=u),'Chamada Principal';
 select jsonb_agg(jsonb_build_object('grupo',grupo,'data_inicio',case when grupo='principal' then hoje-1 else data_inicio end,'data_fim',case when grupo='banco_terca' then hoje-1 else data_fim end) order by data_inicio) into ps from public.desenvolvimento_periodos where usuario_id=u;
 perform public.salvar_periodos_desenvolvimento(u,ps);
 assert exists(select 1 from public.usuario_funcoes where usuario_id=u and funcao_id=principal),'Correção alterou a função';
 assert (select data_corrente_principal=hoje-1 from public.usuarios where id=u),'Data corrigida no resumo';
 perform public.salvar_funcoes_com_periodo(u,extras||array[pai,sabado]);
 perform public.salvar_funcoes_com_periodo(u,extras||array[pai,corrente]);
 assert (select count(*)=1 from public.desenvolvimento_periodos where usuario_id=u and data_inicio=hoje),'Duplicidade no mesmo dia';
 assert exists(select 1 from public.desenvolvimento_periodos where usuario_id=u and grupo='corrente_terca' and data_fim is null),'Retorno à terça';
 perform public.salvar_funcoes_com_periodo(u,extras);
 assert exists(select 1 from public.desenvolvimento_periodos where usuario_id=u and grupo='fora' and data_fim is null),'Saída da corrente';
 assert not exists(select 1 from public.listar_associados_presenca_periodo(lista_dev,hoje) where id=u),'Saída ainda na lista';
 assert (select count(*)=antes from public.presencas),'Presenças modificadas';
 perform set_config('request.jwt.claim.sub','',true);
 begin perform public.salvar_funcoes_com_periodo(u,extras); exception when others then falhou:=true; end;
 assert falhou,'Sem sessão conseguiu alterar funções';
end $$;
select 'OK: funções liberadas, data automática, transferência Principal, retorno, saída, correção no resumo e presenças preservadas' as teste;
rollback;
